use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// An empirical trajectory record from historical protocol evaluations.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrajectoryEvent {
    pub event_id: String,
    pub rfc_number: u32,
    pub section: String,
    pub mutation_type: String,
    pub is_anomalous: bool,
    pub divergence_score: f64,
    pub reproducibility_rate: f64,
    pub latency_ms: f64,
    pub finding_status: String,
    pub timestamp: u64,
}

/// State transition statistics tracked by the offline World Model for an RFC/mutation pair.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WorldModelTransition {
    pub rfc_number: u32,
    pub mutation_type: String,
    pub sample_count: usize,
    pub alpha_anomalies: f64,
    pub beta_clean: f64,
    pub predicted_divergence: f64,
    pub predicted_reproducibility: f64,
    pub information_entropy: f64,
    pub last_updated: u64,
}

/// Research Policy defining prioritization weights for RFC scanning.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResearchPolicy {
    pub policy_id: String,
    pub generation: usize,
    pub rfc_weights: HashMap<u32, f64>,
    pub mutation_weights: HashMap<String, f64>,
    pub default_trial_budget: u32,
    pub exploration_temperature: f64,
    pub fitness_score: f64,
    pub created_at: u64,
}

impl Default for ResearchPolicy {
    fn default() -> Self {
        let mut rfc_weights = HashMap::new();
        rfc_weights.insert(9110, 1.0); // HTTP Semantics
        rfc_weights.insert(9112, 1.2); // HTTP/1.1 Framing & Delimiting
        rfc_weights.insert(7230, 0.9); // Legacy HTTP/1.1
        rfc_weights.insert(7540, 1.1); // HTTP/2
        rfc_weights.insert(9113, 1.1); // HTTP/2 Revision

        let mut mutation_weights = HashMap::new();
        mutation_weights.insert("abnf_delimiter".to_string(), 1.0);
        mutation_weights.insert("header_smuggling".to_string(), 1.2);
        mutation_weights.insert("case_mutation".to_string(), 0.7);
        mutation_weights.insert("crlf_injection".to_string(), 1.3);
        mutation_weights.insert("duplicate_header".to_string(), 0.8);
        mutation_weights.insert("null_byte".to_string(), 0.9);
        mutation_weights.insert("chunk_extension".to_string(), 1.1);

        Self {
            policy_id: "policy-initial-default".to_string(),
            generation: 0,
            rfc_weights,
            mutation_weights,
            default_trial_budget: 3,
            exploration_temperature: 0.25,
            fitness_score: 0.5,
            created_at: 0,
        }
    }
}

/// Rollout simulation summary from testing a policy in the "dream" (world model).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DreamRolloutReport {
    pub rollout_id: String,
    pub policy_id: String,
    pub simulated_steps: usize,
    pub projected_yield: f64,
    pub projected_entropy_reduction: f64,
    pub projected_reproducibility: f64,
    pub simulated_anomalies_discovered: usize,
    pub simulated_false_positives_filtered: usize,
    pub duration_ms: u64,
}

/// Concrete research experiment recommendation generated by Arm 110 for Arm 107.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RsiExperimentPlan {
    pub plan_id: String,
    pub generated_at: u64,
    pub policy_generation: usize,
    pub prioritized_rfcs: Vec<RfcPriorityItem>,
    pub prioritized_mutations: Vec<MutationPriorityItem>,
    pub recommended_trial_budget: u32,
    pub estimated_discovery_yield: f64,
    pub rationale: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RfcPriorityItem {
    pub rfc_number: u32,
    pub title: String,
    pub priority_score: f64,
    pub recommended_sections: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MutationPriorityItem {
    pub mutation_type: String,
    pub weight: f64,
    pub historical_divergence_rate: f64,
}

/// Status DTO for Dream-RSI Arm (Arm 110).
